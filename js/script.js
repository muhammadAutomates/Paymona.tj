// --- CATALOG PAGE CONTROLLER ---
let currentFilter = 'all';
let searchQuery = '';

function initGlobalSearch() {
    const params = new URLSearchParams(window.location.search);
    const searchParam = params.get('search');
    
    // 1. Pre-fill and expand if active query exists
    if (searchParam) {
        searchQuery = searchParam;
        document.querySelectorAll('.search-input').forEach(input => {
            input.value = searchParam;
        });
        document.querySelectorAll('.search-container').forEach(container => {
            container.classList.add('active');
        });
    }
    
    // 2. Bind search inputs events
    const searchInputs = document.querySelectorAll('.search-input');
    searchInputs.forEach(input => {
        input.addEventListener('input', (e) => {
            searchQuery = e.target.value;
            // Sync all search inputs across page
            searchInputs.forEach(i => { if (i !== input) i.value = searchQuery; });
            
            // Trigger dynamic filter if we are on the catalog page
            if (document.getElementById('productsGrid')) {
                renderCatalog();
            }
        });

        input.addEventListener('keydown', (e) => {
            if (e.key === 'Enter') {
                const query = e.target.value.trim();
                window.location.href = `catalog.html?search=${encodeURIComponent(query)}`;
            }
        });
    });
    
    // 3. Bind search buttons click events with mobile expand toggle
    document.querySelectorAll('.search-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const container = btn.parentElement;
            const input = container.querySelector('.search-input');
            if (input) {
                // Mobile viewport toggle behavior
                if (window.innerWidth <= 640) {
                    if (!container.classList.contains('active')) {
                        e.preventDefault();
                        container.classList.add('active');
                        setTimeout(() => input.focus(), 150);
                        return;
                    }
                }
                
                const query = input.value.trim();
                
                // Collapse if empty
                if (query === '' && window.innerWidth <= 640) {
                    container.classList.remove('active');
                    input.blur();
                    return;
                }
                
                window.location.href = `catalog.html?search=${encodeURIComponent(query)}`;
            }
        });
    });
    
    // 4. Close mobile search when clicking outside
    document.addEventListener('click', (e) => {
        if (!e.target.closest('.search-container')) {
            document.querySelectorAll('.search-container').forEach(container => {
                if (container.classList.contains('active')) {
                    const input = container.querySelector('.search-input');
                    if (input && input.value.trim() === '') {
                        container.classList.remove('active');
                    }
                }
            });
        }
    });
}

function initCatalogPage() {
    const catalogGrid = document.getElementById('productsGrid');
    if (!catalogGrid) return;
    
    // Parse URL parameters
    const params = new URLSearchParams(window.location.search);
    const catParam = params.get('category');
    
    if (catParam) currentFilter = catParam;
    
    // Bind Catalog Category Filter buttons
    const filterBtns = document.querySelectorAll('.filter-btn');
    filterBtns.forEach(btn => {
        const filterVal = btn.getAttribute('data-filter');
        // Match active filter visually on reload
        if (filterVal === currentFilter) {
            filterBtns.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
        }
        
        btn.addEventListener('click', () => {
            filterBtns.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            currentFilter = filterVal;
            renderCatalog();
        });
    });
    
    // Initial Catalog Render
    renderCatalog();
    
    // Also listen to lang change to translate names dynamically in catalog grid
    document.getElementById('langSelect')?.addEventListener('change', renderCatalog);
}

function renderCatalog() {
    const catalogGrid = document.getElementById('productsGrid');
    const noResults = document.getElementById('noResults');
    if (!catalogGrid) return;
    
    const filtered = storeProducts.filter(p => {
        if (p.isActive === false) return false;
        const matchesCat = currentFilter === 'all' || p.category === currentFilter;
        const matchesSearch = p.name.toLowerCase().includes(searchQuery.toLowerCase()) || 
                              (p.description && p.description.toLowerCase().includes(searchQuery.toLowerCase()));
        return matchesCat && matchesSearch;
    });
    
    catalogGrid.innerHTML = '';
    
    if (filtered.length === 0) {
        if (noResults) noResults.classList.remove('hidden');
    } else {
        if (noResults) noResults.classList.add('hidden');
        filtered.forEach(p => {
            catalogGrid.appendChild(createProductCard(p));
        });
        // Trigger scroll reveals for catalog items
        initScrollReveal();
    }
}

// Update Showcase item in Hero
function updateHeroShowcase() {
    const showImg = document.getElementById('heroShowcaseImage');
    const showName = document.getElementById('heroShowcaseName');
    const showPrice = document.getElementById('heroShowcasePrice');
    const showCard = document.getElementById('heroShowcaseCard');
    
    if (!showImg || storeProducts.length === 0) return;
    
    // Choose the mixer ( Bergamo ) or first hit product
    const featured = storeProducts.find(p => p.id === 15 && p.isActive !== false) || storeProducts.find(p => p.badge === 'Хит' && p.isActive !== false) || storeProducts.find(p => p.isActive !== false);
    
    if (featured) {
        showImg.src = featured.image;
        showImg.alt = featured.name;
        showName.textContent = featured.name;
        showPrice.textContent = `${featured.price} c.`;
        
        // Clicking review button triggers product modal details
        showCard.addEventListener('click', () => {
            openProductDetailModal(featured.id);
        });
    }
}

// Render popular products (Hits)
function renderPopularProducts() {
    const grid = document.getElementById('popularProductsGrid');
    if (!grid) return;
    
    grid.innerHTML = '';
    const hits = storeProducts.filter(p => p.isActive !== false && (p.badge === 'Хит' || p.id % 7 === 0)).slice(0, 4);
    
    if (hits.length === 0) {
        grid.innerHTML = '<p class="text-center w-100" data-i18n="catalog_empty">Товары загружаются...</p>';
        translatePage();
        return;
    }
    
    hits.forEach(p => {
        grid.appendChild(createProductCard(p));
    });
    
    // Trigger scroll reveals for dynamic elements
    initScrollReveal();
}

// Helper to construct a beautiful Product Card HTML node
function createProductCard(p) {
    const lang = getCurrentLang();
    const card = document.createElement('div');
    card.className = 'product-card scroll-reveal reveal-scale';
    
    // Badges setup
    let badgeHtml = '';
    if (p.badge) {
        const badgeClass = p.badge.toLowerCase() === 'скидка' || p.badge.toLowerCase() === 'распродажа' || p.badge.includes('%') ? 'sale' : 'new';
        badgeHtml = `<div class="product-badge ${badgeClass}">${p.badge}</div>`;
    }
    
    // Compute pricing layouts
    let priceHtml = `<span class="product-price">${p.price} c.</span>`;
    if (p.oldPrice) {
        priceHtml = `
            <div class="price-stack">
                <span class="product-price">${p.price} c.</span>
                <span class="old-price">${p.oldPrice} c.</span>
            </div>
        `;
    }
    
    card.innerHTML = `
        ${badgeHtml}
        <div class="product-image-wrap">
            <img src="${p.image}" alt="${p.name}" class="product-image" loading="lazy">
        </div>
        <div class="product-info">
            <span class="product-category" data-i18n="cat_${p.category}">${i18n[lang][`cat_${p.category}`] || p.category}</span>
            <h3 class="product-name">${p.name}</h3>
            <div class="product-rating-row">
                <div class="product-rating">
                    <i class="ph-fill ph-star"></i><i class="ph-fill ph-star"></i><i class="ph-fill ph-star"></i><i class="ph-fill ph-star"></i><i class="ph-fill ph-star"></i>
                </div>
                <span class="rating-count">(5)</span>
            </div>
            <div class="product-price-row">
                ${priceHtml}
                <button class="add-to-cart-btn" aria-label="Add to cart"><i class="ph ph-shopping-cart-simple"></i></button>
            </div>
        </div>
    `;
    
    // Card image or title clicks trigger detailed product popup
    const imgWrap = card.querySelector('.product-image-wrap');
    const nameWrap = card.querySelector('.product-name');
    [imgWrap, nameWrap].forEach(el => {
        el.addEventListener('click', () => openProductDetailModal(p.id));
    });
    
    // Add to cart quick actions
    const addBtn = card.querySelector('.add-to-cart-btn');
    addBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        
        // If product has variations (colors or sizes), force opening the modal so they choose options
        if ((p.colors && p.colors.length > 0) || (p.sizes && p.sizes.length > 0)) {
            openProductDetailModal(p.id);
        } else {
            addToCart(p, 1, '', '');
            
            // Success animation
            const originalIcon = addBtn.innerHTML;
            addBtn.innerHTML = '<i class="ph ph-check"></i>';
            addBtn.style.backgroundColor = 'var(--brand-red)';
            addBtn.style.color = 'white';
            addBtn.style.borderColor = 'var(--brand-red)';
            
            setTimeout(() => {
                addBtn.innerHTML = originalIcon;
                addBtn.style.backgroundColor = '';
                addBtn.style.color = '';
                addBtn.style.borderColor = '';
            }, 1200);
        }
    });
    
    return card;
}

// --- LANGUAGE PICKER & TRANSLATOR MODULE ---
function setupLanguageSwitcher() {
    const langSelect = document.getElementById('langSelect');
    const customLangSwitcher = document.getElementById('langSwitcher');
    const currentLangBtn = document.getElementById('currentLangBtn');
    const langOptions = document.querySelectorAll('.lang-option');
    const activeLangText = document.getElementById('activeLangText');
    
    if (!customLangSwitcher) return;
    
    currentLangBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        customLangSwitcher.classList.toggle('active');
    });
    
    document.addEventListener('click', () => {
        customLangSwitcher.classList.remove('active');
    });
    
    langOptions.forEach(option => {
        option.addEventListener('click', () => {
            const value = option.getAttribute('data-value');
            
            langOptions.forEach(opt => opt.classList.remove('active'));
            option.classList.add('active');
            activeLangText.textContent = value.toUpperCase();
            
            langSelect.value = value;
            langSelect.dispatchEvent(new Event('change'));
        });
    });
    
    langSelect.addEventListener('change', (e) => {
        localStorage.setItem('paymona_lang', e.target.value);
        translatePage();
    });
    
    // Read saved language preference or default to RU
    const savedLang = localStorage.getItem('paymona_lang') || 'ru';
    langSelect.value = savedLang;
    activeLangText.textContent = savedLang.toUpperCase();
    langOptions.forEach(opt => {
        if (opt.getAttribute('data-value') === savedLang) opt.classList.add('active');
        else opt.classList.remove('active');
    });
    translatePage();
}

function translatePage() {
    const lang = getCurrentLang();
    
    // Localize texts
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (i18n[lang] && i18n[lang][key]) {
            el.innerHTML = i18n[lang][key];
        }
    });
    
    // Localize placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (i18n[lang] && i18n[lang][key]) {
            el.setAttribute('placeholder', i18n[lang][key]);
        }
    });
}

// --- WOW BACKGROUND PARTICLES ENGINE ---
function initParticles(canvasId, dotColor) {
    const canvas = document.getElementById(canvasId);
    if (!canvas) return;
    
    const ctx = canvas.getContext('2d');
    let animationFrameId;
    
    // Resize handler
    function resizeCanvas() {
        canvas.width = canvas.parentElement.offsetWidth;
        canvas.height = canvas.parentElement.offsetHeight;
    }
    resizeCanvas();
    window.addEventListener('resize', resizeCanvas);
    
    const particles = [];
    const count = 35;
    
    class Particle {
        constructor() {
            this.x = Math.random() * canvas.width;
            this.y = Math.random() * canvas.height;
            this.radius = Math.random() * 2 + 1;
            this.vx = (Math.random() - 0.5) * 0.4;
            this.vy = (Math.random() - 0.5) * 0.4;
            this.alpha = Math.random() * 0.5 + 0.2;
        }
        
        update() {
            this.x += this.vx;
            this.y += this.vy;
            
            if (this.x < 0 || this.x > canvas.width) this.vx *= -1;
            if (this.y < 0 || this.y > canvas.height) this.vy *= -1;
        }
        
        draw() {
            ctx.beginPath();
            ctx.arc(this.x, this.y, this.radius, 0, Math.PI * 2);
            ctx.fillStyle = dotColor.replace('ALPHA', this.alpha);
            ctx.fill();
        }
    }
    
    for (let i = 0; i < count; i++) {
        particles.push(new Particle());
    }
    
    function animate() {
        ctx.clearRect(0, 0, canvas.width, canvas.height);
        
        // Draw connections
        for (let i = 0; i < particles.length; i++) {
            particles[i].update();
            particles[i].draw();
            
            for (let j = i + 1; j < particles.length; j++) {
                const dist = Math.hypot(particles[i].x - particles[j].x, particles[i].y - particles[j].y);
                if (dist < 120) {
                    const linkAlpha = (1 - dist / 120) * 0.15;
                    ctx.beginPath();
                    ctx.moveTo(particles[i].x, particles[i].y);
                    ctx.lineTo(particles[j].x, particles[j].y);
                    ctx.strokeStyle = dotColor.replace('ALPHA', linkAlpha);
                    ctx.stroke();
                }
            }
        }
        
        animationFrameId = requestAnimationFrame(animate);
    }
    animate();
    
    // Pause animation when tab is hidden (Page Visibility API)
    document.addEventListener('visibilitychange', () => {
        if (document.hidden) {
            cancelAnimationFrame(animationFrameId);
        } else {
            animate();
        }
    });
    
    // Store handle to cancel if needed
    canvas.dataset.animationId = animationFrameId;
}



