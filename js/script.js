// --- PRODUCT REVIEWS MODULE ---
async function loadProductReviews(productId) {
    const list = document.getElementById('reviewsList');
    const starsRow = document.getElementById('detailRatingStars');
    const countEl = document.getElementById('detailRatingCount');
    if (!list) return;
    
    list.innerHTML = '';
    
    let reviews = [];
    try {
        const response = await fetch(`/api/reviews/${productId}`);
        if (response.ok) {
            reviews = await response.json();
        }
    } catch(err) {
        // Offline fallback
        reviews = [];
    }
    
    // Update reviews stars average metrics
    let avg = 5;
    if (reviews.length > 0) {
        const sum = reviews.reduce((acc, r) => acc + r.rating, 0);
        avg = Math.round((sum / reviews.length) * 10) / 10;
        
        // Write lists
        reviews.forEach(r => {
            const item = document.createElement('div');
            item.className = 'review-item';
            
            const starsHTML = '<i class="ph-fill ph-star"></i>'.repeat(r.rating) + '<i class="ph ph-star"></i>'.repeat(5 - r.rating);
            const dateStr = new Date(r.date).toLocaleDateString('ru-RU');
            
            item.innerHTML = `
                <div class="review-meta">
                    <span class="review-author">${r.name}</span>
                    <span class="review-date">${dateStr}</span>
                </div>
                <div class="review-rating">${starsHTML}</div>
                <p class="review-text">${r.comment}</p>
            `;
            list.appendChild(item);
        });
    } else {
        list.innerHTML = `<p class="text-center" style="grid-column: span 2; color:var(--text-muted); padding:20px;">Нет отзывов. Будьте первыми! / Фикру мулоҳиза нест. Аввалин бошед!</p>`;
    }
    
    // Update Stars in modal header
    const roundedAvg = Math.round(avg);
    if(starsRow) {
        starsRow.innerHTML = '<i class="ph-fill ph-star"></i>'.repeat(roundedAvg) + '<i class="ph ph-star"></i>'.repeat(5 - roundedAvg);
    }
    if(countEl) {
        countEl.textContent = `(${reviews.length})`;
    }
}

