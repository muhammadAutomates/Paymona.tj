// Initialize Session Token for Active Visitors metrics
function getSessionToken() {
    let token = sessionStorage.getItem('paymona_visitor_token');
    if (!token) {
        token = 'v_' + Math.random().toString(36).substring(2, 15) + Date.now();
        sessionStorage.setItem('paymona_visitor_token', token);
    }
    return token;
}

